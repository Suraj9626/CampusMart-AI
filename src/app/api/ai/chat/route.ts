import { NextRequest, NextResponse } from "next/server";
import { GoogleGenAI } from "@google/genai";

const SYSTEM_INSTRUCTION = `You are the CampusMart AI Assistant, a friendly, intelligent, and trustworthy AI assistant embedded directly inside "CampusMart AI" — an exclusive, verified marketplace and auction platform for college students.

Your capabilities:
1. PLATFORM KNOWLEDGE:
   - Answer questions about how CampusMart AI works: buying, selling, bidding, anti-sniping protection, private messaging, campus safe pickup zones, and student verification.
   - Platform rules: Only students with approved college emails (.edu) can register. Transactions are arranged on-campus (e.g. library, student union, police station safe exchange zones).
   - Auctions: Sellers set a starting bid, optional reserve price (secret minimum), and duration. Bids have atomic server validation. If a bid occurs in the last 2 minutes, anti-sniping automatically extends the auction by 3 minutes!
   - Privacy: Student contact information (phone, personal email) is protected. All negotiations happen through secure on-platform private messaging.
   - Safety & Item guidelines: The platform is designed for carryable college student items (laptops, tablets, chargers, textbooks, calculators, lab coats, backpacks, foldable stands, study lamps). Heavy furniture and bulky appliances (like large refrigerators or heavy desks) are not suitable for campus handoffs.
   - Pricing: All pricing is in Indian Rupees (₹ INR). Second-hand student deals on campus are budget-friendly and low (typically ranging from ₹200 to ₹3,500). When giving price estimates, recommend fair, affordable student prices in ₹ INR.
2. GENERAL KNOWLEDGE & ACADEMIC ASSISTANCE:
   - Help students with coursework, coding, computer science algorithms, engineering formulas, mathematics, exam revision tips, essay brainstorming, and study hacks.
   - Provide clear, well-formatted markdown responses with code blocks, bullet points, and practical explanations.
3. SAFETY & INTEGRITY:
   - Always encourage safe, daylight exchanges in public campus areas.
   - Warn against wire transfers, Venmo with strangers before inspecting items, or off-platform communication scams.
   - You do NOT directly execute purchases or bids; guide the user to the proper UI buttons on the listing page.

Be concise, supportive, professional, and collegiate.`;

export async function POST(req: NextRequest) {
  try {
    const { messages, userMessage } = await req.json();

    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { error: "Gemini API key is not configured on the server." },
        { status: 500 }
      );
    }

    const client = new GoogleGenAI({ apiKey });

    // Build conversation context
    let promptText = `${SYSTEM_INSTRUCTION}\n\n`;
    if (Array.isArray(messages) && messages.length > 0) {
      messages.slice(-6).forEach((m: { role: string; content: string }) => {
        promptText += `${m.role === 'user' ? 'Student' : 'Assistant'}: ${m.content}\n`;
      });
    }
    promptText += `Student: ${userMessage}\nAssistant:`;

    // Attempt generation with gemini-2.5-flash (verified) or gemini-1.5-flash fallback
    let responseText = "";
    try {
      const response = await client.models.generateContent({
        model: "gemini-2.5-flash",
        contents: promptText,
      });
      responseText = response.text || "";
    } catch (e: any) {
      console.warn("Retrying with gemini-1.5-flash due to:", e?.message);
      const fallbackResponse = await client.models.generateContent({
        model: "gemini-1.5-flash",
        contents: promptText,
      });
      responseText = fallbackResponse.text || "";
    }

    if (!responseText) {
      return NextResponse.json(
        { error: "No response was generated by the AI model." },
        { status: 502 }
      );
    }

    return NextResponse.json({ reply: responseText });
  } catch (error: any) {
    console.error("AI Chat Route Error:", error);
    return NextResponse.json(
      { error: error?.message || "Failed to process AI assistant request. Please try again." },
      { status: 500 }
    );
  }
}
